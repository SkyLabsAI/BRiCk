#!/usr/bin/env bash
# Record toolchain configuration or generate a thin command adapter for cpp2v-run.
set -euo pipefail

fail() { echo "cpp2v-toolchain: $*" >&2; exit 2; }
absolute_file() {
    local directory
    directory=$(dirname "$1")
    printf '%s/%s\n' "$(cd "$directory" && pwd -P)" "${1##*/}"
}
file_hash() {
    if [[ ! -f $1 ]]; then printf 'unavailable\n'; return; fi
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d ' ' -f 1
    else
        shasum -a 256 "$1" | cut -d ' ' -f 1
    fi
}

command=${1:-}
[[ $# -gt 0 ]] && shift
case "$command" in
    configure)
        image=
        image_set=n
        default_image=
        platform=
        opam=n
        workspace=${DUNE_SOURCEROOT:-$PWD}
        while [[ $# -gt 0 ]]; do
            case "$1" in
                --image|--default-image|--platform|--workspace)
                    [[ $# -ge 2 ]] || fail "missing value for $1"
                    case "$1" in
                        --image) image=$2; image_set=y ;;
                        --default-image) default_image=$2 ;;
                        --platform) platform=$2 ;;
                        --workspace) workspace=$2 ;;
                    esac
                    shift 2
                    ;;
                --opam) opam=y; shift ;;
                *) fail "unknown configure option: $1" ;;
            esac
        done
        mode=${CPP2V_DOCKER_ENABLED-n}
        case "$mode" in n|y) ;; *) fail "CPP2V_DOCKER_ENABLED must be n or y" ;; esac
        # Explicit --image > environment > consumer default, even for empty values.
        if [[ $image_set == n ]]; then image=${CPP2V_DOCKER_IMAGE-$default_image}; fi
        image_ref=$image
        # Do not contact Docker at all for the default host-backed configuration.
        # Only pin a cached ID when the requested platform is available. Keep
        # the reference pullable otherwise, including on Docker versions that
        # do not support platform-aware inspection.
        if [[ $mode != n && -n $image ]] && command -v docker >/dev/null 2>&1; then
            # Keep the top-level ID: a platform-specific ID may identify a child
            # descriptor that Docker cannot run directly. Check that same ID to
            # avoid a tag changing between the two inspections.
            if image_id=$(docker image inspect --format='{{.Id}}' "$image" 2>/dev/null) && [[ -n $image_id ]]; then
                if [[ -z $platform ]]; then
                    image=$image_id
                # Inspect can succeed for an uncached descriptor; its config
                # (including Architecture) is populated only when available.
                elif image_arch=$(docker image inspect --platform "$platform" \
                    --format='{{.Architecture}}' "$image_id" 2>/dev/null) && [[ -n $image_arch ]]; then
                    image=$image_id
                fi
            fi
        fi
        user=${CPP2V_DOCKER_USER:-$(id -u):$(id -g)}
        workspace=$(cd "$workspace" && pwd -P)
        printf '# Generated by cpp2v-toolchain configure.\n'
        printf 'cpp_env_version=1\ncpp_env_mode=%q\ncpp_env_image=%q\n' "$mode" "$image"
        printf 'cpp_env_image_ref=%q\ncpp_env_user=%q\n' "$image_ref" "$user"
        printf 'cpp_env_platform=%q\ncpp_env_opam=%q\ncpp_env_workspace=%q\n' "$platform" "$opam" "$workspace"
        ;;
    wrapper)
        runner=
        config=
        config_set=n
        config_from_argument=n
        host_tool=
        container_tool=
        while [[ $# -gt 0 ]]; do
            case "$1" in
                --runner|--config|--host-tool|--container-tool)
                    [[ $# -ge 2 ]] || fail "missing value for $1"
                    case "$1" in
                        --runner) runner=$2 ;;
                        --config) config=$2; config_set=y ;;
                        --host-tool) host_tool=$2 ;;
                        --container-tool) container_tool=$2 ;;
                    esac
                    shift 2
                    ;;
                --config-from-argument) config_from_argument=y; shift ;;
                *) fail "unknown wrapper option: $1" ;;
            esac
        done
        [[ -n $host_tool ]] || fail "--host-tool is required"
        [[ -n $runner && -x $runner ]] || fail "--runner must name an executable"
        if [[ $config_from_argument == y ]]; then
            [[ $config_set == n ]] || fail "--config and --config-from-argument are mutually exclusive"
        else
            [[ -n $config && -r $config ]] || fail "--config must name a readable configuration"
            config=$(absolute_file "$config")
        fi
        [[ -n $container_tool ]] || fail "--container-tool is required"
        runner=$(absolute_file "$runner")
        case "$host_tool" in
            */*) host_tool=$(absolute_file "$host_tool") ;;
            *)
                # A Docker-only compiler need not be installed on the host.
                resolved=$(type -P "$host_tool" || true)
                if [[ -n $resolved ]]; then host_tool=$(absolute_file "$resolved"); fi
                ;;
        esac
        printf '#!/usr/bin/env bash\n# host tool: %s\n' "$(file_hash "$host_tool")"
        printf '# runner: %s\n' "$(file_hash "$runner")"
        if [[ $config_from_argument == n ]]; then
            printf '# configuration: %s\n' "$(file_hash "$config")"
            # shellcheck disable=SC2016 # The adapter expands "$@".
            printf 'exec %q --config %q --host-tool %q --container-tool %q -- "$@"\n' \
                "$runner" "$config" "$host_tool" "$container_tool"
        else
            [[ -f $host_tool && -x $host_tool ]] || fail "--config-from-argument requires an executable host tool"
            printf 'set -euo pipefail\n'
            declare -f fail absolute_file file_hash
            # Installed Rocq resources must not depend on their build checkout
            # surviving. Relocation may use PATH only for byte-identical tools,
            # never an untracked replacement or a host fallback for Docker.
            cat <<'EOF'
resolve_tool() {
    local recorded=$1 expected=$2 name=$3 candidate
    if [[ -f $recorded && -x $recorded && $(file_hash "$recorded") == "$expected" ]]; then
        printf '%s\n' "$recorded"
        return
    fi
    candidate=$(type -P "$name" || true)
    if [[ -n $candidate && -f $candidate && -x $candidate && $(file_hash "$candidate") == "$expected" ]]; then
        absolute_file "$candidate"
        return
    fi
    fail "cannot locate the recorded $name executable (or a byte-identical installed copy)"
}
[[ $# -gt 0 ]] || fail "expected a toolchain configuration as the first argument"
config=$1
shift
EOF
            # The source may be cpp2v-run.sh; its installed command is cpp2v-run.
            printf 'runner=$(resolve_tool %q %q %q)\n' "$runner" "$(file_hash "$runner")" cpp2v-run
            printf 'host_tool=$(resolve_tool %q %q %q)\n' "$host_tool" "$(file_hash "$host_tool")" "${host_tool##*/}"
            # shellcheck disable=SC2016 # Variables are expanded by the adapter.
            printf 'exec "$runner" --config "$config" --host-tool "$host_tool" --container-tool %q -- "$@"\n' "$container_tool"
        fi
        ;;
    *) fail "usage: cpp2v-toolchain {configure|wrapper} [options]" ;;
esac
